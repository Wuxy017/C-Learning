int;
//int 是英文 integer（整数） 的缩写。在 C 语言里，它是用来装整数的容器。
//它能装：0、23、-100、99999
//它不能装：3.14（小数）、'A'（字符）、"hello"（字符串）
int price;      // 声明一个叫 price 的变量，它只能装整数
int change;     // 再声明一个 change，也用来装整数
int a = 10;     // 声明 a，并直接塞进去一个 10

//装整数的盒子 = int
//装小数的盒子 = float 或 double
//装单个字母的盒子 = char
//什么都不返回的函数 = void

return 0;

//return：返回。把后面的东西交出去。
//0：交出去的具体数字。在 C 语言里，0 代表“成功/正常”，非 0 的数字（比如 1、-1）通常代表“出错”。
//;：结束这一行。

//return 0; 必须写在 main 函数的最后（大括号 } 前面）。
//它不能写在 printf 中间，否则 printf 后面的代码就永远执行不到了。
//记得加英文分号，别漏了。

int main();

//“我是一个名叫 main 的主函数，我执行完之后，会向操作系统交回一个整数（通常用 return 0; 来代表‘一切顺利’）。”
//🧩 拆开记：
//int：承诺交回一个整数（状态码）。
//main：函数的名字，固定不变，是程序的唯一入口。
//()：暂时不接收外部参数。
//{}：里面装着你所有的代码。
//return 0;：履行承诺，交回 0，代表“正常完工”。